-- Push-подписки для уведомлений о статусе заказа
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  order_guid text,
  user_agent text
);

create index if not exists push_subscriptions_order_guid_idx
  on public.push_subscriptions (order_guid);

alter table public.push_subscriptions enable row level security;

-- Читать и писать подписки может только service_role через Edge Functions.
-- Публичных политик нет.

-- Администратор может удалять тестовые/старые записи мониторинга.
drop policy if exists client_errors_admin_delete on public.client_errors;
create policy client_errors_admin_delete
  on public.client_errors
  for delete
  to authenticated
  using (coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin');
