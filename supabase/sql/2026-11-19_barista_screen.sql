-- Экран бариста: состав заказа, отметки «Готово» / «Выдан», журнал действий.
--
-- Порядок применения:
--   1. Выполнить этот файл в Supabase SQL Editor.
--   2. Задеплоить обновлённую функцию create-order.
--   3. Создать учётные записи бариста в Supabase Auth и выдать им
--      app_metadata.role = 'barista' (владельцу оставить 'admin').
--
-- Функции security definer проверяют роль по JWT. Прямой доступ к orders
-- и order_events у роли authenticated не расширяется.

alter table public.orders
  add column if not exists items_summary text,
  add column if not exists guest_comment text,
  add column if not exists barista_status text,
  add column if not exists ready_at timestamptz,
  add column if not exists handed_at timestamptz,
  add column if not exists barista_id uuid;

alter table public.orders drop constraint if exists orders_barista_status_check;
alter table public.orders
  add constraint orders_barista_status_check
  check (barista_status is null or barista_status in ('ready', 'handed'));

create index if not exists orders_barista_queue_idx
  on public.orders (created_at desc)
  where status <> 'failed';

create table if not exists public.order_events (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  actor_id uuid,
  actor_role text,
  event text not null,
  created_at timestamptz not null default now()
);

alter table public.order_events drop constraint if exists order_events_event_check;
alter table public.order_events
  add constraint order_events_event_check
  check (event in ('ready', 'handed', 'reset'));

create index if not exists order_events_order_id_idx
  on public.order_events (order_id, created_at desc);

alter table public.order_events enable row level security;
revoke all on public.order_events from anon, authenticated;

create or replace function public.barista_orders()
returns table (
  id bigint,
  order_number text,
  created_at timestamptz,
  customer_name text,
  total numeric,
  items_summary text,
  comment text,
  status text,
  payment_status text,
  barista_status text,
  ready_at timestamptz,
  handed_at timestamptz
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_role text := coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '');
begin
  if v_role not in ('barista', 'admin') then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  return query
    select
      o.id,
      o.order_number::text,
      o.created_at,
      o.customer_name,
      o.total::numeric,
      o.items_summary,
      coalesce(o.guest_comment, '') as comment,
      o.status::text,
      o.payment_status::text,
      o.barista_status::text,
      o.ready_at,
      o.handed_at
    from public.orders o
    where o.created_at >= now() - interval '2 days'
      and o.status <> 'failed'
      and (v_role = 'admin' or o.payment_status = 'paid')
    order by o.created_at asc
    limit 200;
end;
$$;

revoke all on function public.barista_orders() from public, anon;
grant execute on function public.barista_orders() to authenticated;

create or replace function public.barista_mark_order(
  p_order_id bigint,
  p_action text
)
returns table (
  id bigint,
  barista_status text,
  ready_at timestamptz,
  handed_at timestamptz
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_role text := coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '');
begin
  if v_role not in ('barista', 'admin') then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  if p_action not in ('ready', 'handed', 'reset') then
    raise exception 'invalid action';
  end if;
  if p_action = 'reset' and v_role <> 'admin' then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  if p_action = 'ready' then
    update public.orders as o
       set barista_status = 'ready',
           ready_at = now(),
           handed_at = null,
           barista_id = auth.uid()
     where o.id = p_order_id
       and o.status <> 'failed'
       and (o.barista_status is null or o.barista_status = 'ready')
       and (v_role = 'admin' or o.payment_status = 'paid');
  elsif p_action = 'handed' then
    update public.orders as o
       set barista_status = 'handed',
           handed_at = now(),
           barista_id = auth.uid()
     where o.id = p_order_id
       and o.status <> 'failed'
       and (o.barista_status = 'ready' or o.barista_status = 'handed')
       and (v_role = 'admin' or o.payment_status = 'paid');
  else
    update public.orders as o
       set barista_status = null,
           ready_at = null,
           handed_at = null,
           barista_id = null
     where o.id = p_order_id;
  end if;

  if not found then
    raise exception 'order not found' using errcode = 'P0002';
  end if;

  insert into public.order_events (order_id, actor_id, actor_role, event)
  values (p_order_id, auth.uid(), v_role, p_action);

  return query
    select
      o.id,
      o.barista_status,
      o.ready_at,
      o.handed_at
    from public.orders o
    where o.id = p_order_id;
end;
$$;

revoke all on function public.barista_mark_order(bigint, text) from public, anon;
grant execute on function public.barista_mark_order(bigint, text) to authenticated;
