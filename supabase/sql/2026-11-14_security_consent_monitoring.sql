-- Согласие на обработку ПД и мониторинг ошибок клиента
alter table public.orders add column if not exists consent boolean not null default false;
alter table public.orders add column if not exists consent_at timestamptz;
alter table public.orders add column if not exists status_message text;

create table if not exists public.client_errors (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  message text not null,
  stack text,
  url text,
  user_agent text
);

create index if not exists client_errors_created_at_idx
  on public.client_errors (created_at desc);

alter table public.client_errors enable row level security;

drop policy if exists client_errors_insert on public.client_errors;
create policy client_errors_insert
  on public.client_errors
  for insert
  to anon, authenticated
  with check (char_length(message) <= 1000);

drop policy if exists client_errors_admin_read on public.client_errors;
create policy client_errors_admin_read
  on public.client_errors
  for select
  to authenticated
  using (coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin');
